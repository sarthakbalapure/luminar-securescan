"use client";

import Link from "next/link";
import { useEffect, useState } from "react";
import { ProtectedShell } from "../../components/protected-shell";
import { Button, Card, EmptyState, ErrorState, Skeleton, StatusBadge } from "../../components/ui";
import { apiRequest, downloadApiFile } from "../../lib/api";
import { formatDate, formatEnum } from "../../lib/security-ui";

type Report = {
  id: string;
  title?: string | null;
  reportType: string;
  reportStatus?: string;
  riskRating?: string | null;
  fileUrl?: string | null;
  generatedAt: string;
  generator?: { name: string; email: string };
  scan: {
    id: string;
    status: string;
    securityScore?: string | number | null;
    completedAt?: string | null;
    asset: {
      name: string;
      url: string;
      project: { name: string; organization: { name: string } };
    };
    _count?: { findings: number };
  };
};

export default function ReportsPage() {
  const [reports, setReports] = useState<Report[]>([]);
  const [loading, setLoading] = useState(true);
  const [downloading, setDownloading] = useState("");
  const [deleting, setDeleting] = useState("");
  const [error, setError] = useState("");

  useEffect(() => {
    apiRequest<Report[]>("/reports")
      .then(setReports)
      .catch((nextError) => setError(nextError instanceof Error ? nextError.message : "Reports could not be loaded."))
      .finally(() => setLoading(false));
  }, []);

  async function download(report: Report) {
    setDownloading(report.id);
    setError("");
    try {
      await downloadApiFile(`/reports/${report.id}/download`, `luminar-securescan-${report.reportType.toLowerCase()}-${report.scan.id}.pdf`);
    } catch (nextError) {
      setError(nextError instanceof Error ? nextError.message : "Report could not be downloaded.");
    } finally {
      setDownloading("");
    }
  }

  async function remove(report: Report) {
    if (!window.confirm(`Delete ${report.title ?? "this report"}?`)) return;
    setDeleting(report.id);
    setError("");
    try {
      await apiRequest(`/reports/${report.id}`, { method: "DELETE" });
      setReports((current) => current.filter((item) => item.id !== report.id));
    } catch (nextError) {
      setError(nextError instanceof Error ? nextError.message : "Report could not be deleted.");
    } finally {
      setDeleting("");
    }
  }

  return (
    <ProtectedShell>
      <div className="mb-6">
        <p className="text-sm font-semibold text-signal">Reports</p>
        <h1 className="text-3xl font-semibold text-ink">Security reports</h1>
        <p className="mt-1 text-sm text-slate-600">Download executive, technical, and full audit reports generated from completed scan evidence.</p>
      </div>
      {error ? <ErrorState message={error} /> : null}
      {loading ? <Skeleton className="h-72" /> : null}
      {!loading && !reports.length ? <EmptyState title="No reports generated yet" detail="Open a scan result and generate an executive, technical, or full audit report." /> : null}
      <div className="grid gap-4 md:grid-cols-2">
        {reports.map((report) => (
          <Card key={report.id}>
            <div className="flex items-start justify-between gap-3">
              <div>
                <p className="text-sm font-semibold text-signal">{formatEnum(report.reportType)}</p>
                <h2 className="mt-1 font-semibold text-ink">{report.title ?? report.scan.asset.name}</h2>
                <p className="mt-1 text-sm text-slate-600">{report.scan.asset.url}</p>
              </div>
              <StatusBadge status={report.scan.status} />
            </div>
            <div className="mt-4 grid grid-cols-2 gap-3 text-sm sm:grid-cols-4">
              <Meta label="Score" value={String(report.scan.securityScore ?? "N/A")} />
              <Meta label="Risk" value={report.riskRating ?? "N/A"} />
              <Meta label="Findings" value={String(report.scan._count?.findings ?? 0)} />
              <Meta label="Generated" value={formatDate(report.generatedAt)} />
            </div>
            <div className="mt-4 rounded-md border border-slate-200 p-3 text-sm">
              <p className="font-medium text-ink">{report.scan.asset.project.organization.name}</p>
              <p className="mt-1 text-slate-600">{report.scan.asset.project.name}</p>
              {report.generator ? <p className="mt-1 text-xs text-slate-500">Generated by {report.generator.name}</p> : null}
            </div>
            <div className="mt-5 flex flex-wrap gap-3">
              <Link className="inline-flex h-10 items-center rounded-md bg-white px-4 text-sm font-medium text-ink ring-1 ring-slate-300 hover:bg-slate-50" href={`/reports/${report.id}`}>View HTML</Link>
              <Button disabled={downloading === report.id} onClick={() => download(report)}>
                {downloading === report.id ? "Downloading..." : "Download PDF"}
              </Button>
              <Button className="bg-white text-ink ring-1 ring-slate-300 hover:bg-slate-50" onClick={() => downloadApiFile(`/reports/${report.id}/findings.csv`, `luminar-findings-${report.id}.csv`)}>CSV</Button>
              <Button className="bg-white text-ink ring-1 ring-slate-300 hover:bg-slate-50" onClick={() => downloadApiFile(`/reports/${report.id}/json`, `luminar-report-${report.id}.json`)}>JSON</Button>
              <Button className="bg-red-700 hover:bg-red-800" disabled={deleting === report.id} onClick={() => remove(report)}>{deleting === report.id ? "Deleting..." : "Delete"}</Button>
            </div>
          </Card>
        ))}
      </div>
    </ProtectedShell>
  );
}

function Meta({ label, value }: { label: string; value: string }) {
  return (
    <div className="rounded-md border border-slate-200 p-3">
      <p className="text-xs uppercase text-slate-500">{label}</p>
      <p className="mt-1 font-semibold text-ink">{value}</p>
    </div>
  );
}
